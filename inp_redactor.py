from pathlib import Path
import time


# - Изменить решатель на итеративный
# - Назначить материал 1300 МПа 0.36 1230 кг/м^3
# - Поставить условие на BOTTOM
# - Поставить условие на START
# - Поставить условие на FINISH
# - Создать точку (2.5, 7., 2.5)
# - Создать MPC Constraint
# - Создать силу (0, -1000, 0)

# Порядок Node Set: Roof, Bottom, Start, Finish

def inp_redactor(out_name, in_name, work_dir, delete_in_file = True, print_done = False):
    if print_done:
        start_time = time.perf_counter()

    epigraph = '''*Heading
    ** Job name: cube_job Model name: cube_mesh
    ** Generated by: Abaqus/CAE 2024
    *Preprint, echo=NO, model=NO, history=NO, contact=NO
    **
    ** PARTS
    **
    *Part, name=PART-1
    *Node'''

    part_and_Assembly_begin = '''** Section: Section-1
    *Solid Section, elset=_PickedSet2, material=Material-1
    ,
    *End Part
    **  
    **
    ** ASSEMBLY
    **
    *Assembly, name=Assembly
    **  
    *Instance, name=PART-1-1, part=PART-1
    *End Instance
    **  
    *Node
          1,          2.5,          7.,          2.5
    *Nset, nset=m_Set-7
     1,
    *Nset, nset=_PickedSet12, internal, instance=PART-1-1\n'''

    epilogue = '''*Surface, type=NODE, name=_PickedSet12_CNS_, internal
    _PickedSet12, 1.
    ** Constraint: Constraint-1
    *MPC
    TIE, _PickedSet12, m_Set-7
    *End Assembly
    ** 
    ** MATERIALS
    ** 
    *Material, name=Material-1
    *Density
     1.23,
    *Elastic
    1300., 0.36
    ** ----------------------------------------------------------------
    ** 
    ** STEP: Step-1
    ** 
    *Step, name=Step-1, nlgeom=NO, solver=ITERATIVE
    *Static
    1., 1., 1e-05, 1.
    ** 
    ** BOUNDARY CONDITIONS
    ** 
    ** Name: BC-1 Type: Displacement/Rotation
    *Boundary
    _PickedSet14, 4, 4
    _PickedSet14, 5, 5
    _PickedSet14, 6, 6
    ** Name: BC-2 Type: Displacement/Rotation
    *Boundary
    _PickedSet15, 2, 2
    ** Name: BC-3 Type: Displacement/Rotation
    *Boundary
    _PickedSet16, 2, 2
    _PickedSet16, 3, 3
    ** 
    ** LOADS
    ** 
    ** Name: Load-1   Type: Concentrated force
    *Cload
    _PickedSet13, 2, -1000.
    ** 
    ** OUTPUT REQUESTS
    ** 
    *Restart, write, frequency=0
    ** 
    ** FIELD OUTPUT: F-Output-1
    ** 
    *Output, field, variable=PRESELECT
    ** 
    ** HISTORY OUTPUT: H-Output-1
    ** 
    *Output, history, variable=PRESELECT
    *End Step'''

    node_flag = True
    element_flag = True
    prenodeset_flag = True
    roof_set_flag = True
    bottom_set_flag = True
    start_set_flag = True
    happy_end_flag = False
    element_str_count = 0
    prev_line = None

    with open(fr"{work_dir}\\{out_name}.inp", 'w') as out, open(fr"{work_dir}\\{in_name}.inp", 'r') as inp:
        for i, line in enumerate(inp, start=1):
            if i == 1:
                out.write(line)
                out.write(epigraph + '\n')
            elif i in [2, 3, 4]:
                continue
            elif i >= 5 and node_flag:
                if 'Elements' in line:
                    node_flag = False
                    element_str_count = i
                    out.write('*Element, type=C3D4\n')
                else:
                    out.write('      '+line)
            elif i > element_str_count + 1 and element_flag:
                if 'Node sets' in line:
                    element_flag = False
                    elset_number = int(prev_line.split(',')[0])
                else:
                    prev_line = line
                    out.write(line)
            elif not element_flag and prenodeset_flag:
                prenodeset_flag = False
                out.write('*Elset, elset=_PickedSet2, internal, generate\n')
                out.write(f'  1,  {elset_number},   1\n')
                out.write(part_and_Assembly_begin)
            elif not prenodeset_flag and roof_set_flag:
                if 'NSET=node set 2' not in line:
                    out.write(line)
                else:
                    roof_set_flag = False
                    out.write('*Nset, nset=_PickedSet13, internal\n1,\n*Nset, nset=_PickedSet14, internal, instance=PART-1-1\n')
            elif not roof_set_flag and bottom_set_flag:
                if 'NSET=node set 3' not in line:
                    out.write(line)
                else:
                    bottom_set_flag = False
                    out.write('*Nset, nset=_PickedSet15, internal, instance=PART-1-1\n')
            elif not bottom_set_flag and start_set_flag:
                if 'NSET=node set 4' not in line:
                    out.write(line)
                else:
                    start_set_flag = False
                    out.write('*Nset, nset=_PickedSet16, internal, instance=PART-1-1\n')
            elif not start_set_flag:
                out.write(line)

        out.write(epilogue)
        happy_end_flag = True

    if delete_in_file and happy_end_flag:
        Path(fr"{work_dir}\\{in_name}.inp").unlink()

    if print_done:
        elapsed = time.perf_counter() - start_time
        print(f'\nФизика добавлена, время: {elapsed:.2f} c\n')